// midLat — широта, по которой считается сжатие долготы (середина карты).
// Рамка нынешней карты: от Арагона и Гаскони до Котора, от Мальты до Боденского озера.
const WORLD_GEO = { lon0: -2.3, lon1: 19.6, lat0: 35.45, lat1: 47.85, midLat: 42, kmX: 5 / MAP_SCALE, kmY: 10 / MAP_SCALE };
// Рамка, по которой считаются координаты сейчас: у новой карты — WORLD_GEO, у карты из старого сохранения — её собственная
// (карта помнит свою рамку в ow.geo; карты, сделанные до расширения рамки, — LEGACY_GEO).
const GEO = { ...WORLD_GEO };
const LEGACY_GEO = { lon0: 0.4, lon1: 18.7, lat0: 35.45, lat1: 47.85 };
