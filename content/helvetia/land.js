// Край Альп: к югу от этой линии — горы (Альпы Гельвеции), к северу — холмистое Междуречье и Юра.
const HELVETIA_ALPS_EDGE = [[6.1, 45.85], [6.45, 46.15], [6.75, 46.35], [7.2, 46.55], [7.7, 46.7], [8.2, 46.82], [8.6, 46.95], [9.0, 47.05], [9.4, 47.15], [9.9, 47.1]];
// Насколько точка в горах: 0 — у края Альп, 1 — в глубине хребтов.
function helvetiaAlps(lon, lat) {
  const e = HELVETIA_ALPS_EDGE;
  if (lon < e[0][0]) return 0;
  let k = 0;
  while (k < e.length - 2 && lon > e[k + 1][0]) k++;
  const t = Math.max(0, Math.min(1, (lon - e[k][0]) / (e[k + 1][0] - e[k][0])));
  const edgeLat = e[k][1] + (e[k + 1][1] - e[k][1]) * t;
  if (lat >= edgeLat) return 0;
  return Math.max(0, Math.min(1, distToPolyline(lon, lat, e) / 28));
}

