// Речь края: на западе (Во, Женева, нижний Вале) говорят по-романски, прочие — по-аллемански.
function helvetiaSpeech(x, y) {
  const [lon, lat] = xyToGeo(x + 0.5, y + 0.5);
  return lon < 7.15 || (lat < 46.42 && lon < 7.6) ? 'romand' : 'alemannic';
}

