// Где кончаются Тулузские земли и начинается Прованс: по Роне (Арль, Тараскон, Авиньон — на левом берегу,
// Бокер и Вильнёв — на правом; Камарг — арльский).
// Граница — на шаг западнее русла: город, сдвинутый с речной клетки, остаётся на своём берегу.
const RHONE_BANK = [[45.05, 4.8], [44.3, 4.68], [43.95, 4.74], [43.8, 4.62], [43.68, 4.55], [43.55, 4.38], [43.3, 4.38]];
function occitaniaRegion(lon, lat) {
  const b = RHONE_BANK;
  let k = 0;
  while (k < b.length - 2 && lat < b[k + 1][0]) k++;
  const t = Math.max(0, Math.min(1, (b[k][0] - lat) / (b[k][0] - b[k + 1][0])));
  return lon < b[k][1] + (b[k + 1][1] - b[k][1]) * t ? 'languedoc' : 'provence';
}

