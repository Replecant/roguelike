const PARMA_FALL = { y: 1248, m: 2, d: 18 };

function dayOfDate(y, m, d) { return julianToJdn(y, m, d) - CAL_JDN0 + 1; }
function parmaSiege(day = timeInfo().day) { return day < dayOfDate(PARMA_FALL.y, PARMA_FALL.m, PARMA_FALL.d); }
function vittoriaPlace() { return G.over.cities.find(c => c.siege === 'vittoria'); }

// Устаревшие после 18 февраля речи об осаде.
function parmaStale(text) {
  return !parmaSiege() && /Парм|Виттори/.test(text) && /осад|строит|под Пармой|стоят наши|Виттори|отложилась/.test(text);
}
function timely(list) { const out = list.filter(t => !parmaStale(t)); return out.length ? out : list; }

