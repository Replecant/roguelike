// Подойти к Парме во время осады. Возвращает true, если вход перехвачен.
function parmaGate(place) {
  if (place.id !== 'parma' || !parmaSiege()) return false;
  const p = G.player;
  if (!isNight()) {
    log('Парма в осаде. Вокруг стен — имперские шатры, рвы и частокол; у ворот — сарацинские лучники. '
      + 'Днём к городу не подойти. Ночью можно попробовать пробраться — если повезёт и хватит ловкости.', C.orange);
    return true;
  }
  const chance = Math.min(0.9, 0.3 + skillLevel(p, 'stealth') * 0.06 + (p.stats.dex - 5) * 0.03);
  trainSkill(p, 'stealth', 3);
  if (rng.chance(chance)) {
    log('Ты пробираешься ползком между шатрами, переходишь ров по колено в ледяной воде — и у калитки тебя втягивают внутрь. '
      + '«Свой! Свой!» Ты в осаждённой Парме.', C.gold);
    enterCity(place, true);
    return true;
  }
  log('Окрик часового, свист стрелы над головой — тебя заметили! Имперский дозор бросается наперерез.', C.red);
  enterWild('imperial_soldier');
  return true;
}

// Раз в день: дни осады и падение Виттории.
function parmaDaily(day) {
  if (G.flags.parma_fallen || parmaSiege(day)) return;
  G.flags.parma_fallen = true;
  const vit = vittoriaPlace(), parma = G.over.cities.find(c => c.id === 'parma');
  if (vit) vit.razed = true;
  if (parma) addNews({ day, text: 'Пармезанцы вышли из ворот, пока император охотился с соколами, и взяли Витторию. Город-лагерь сожжён, '
    + 'Таддео да Сесса убит, казна и корона императора — в Парме. Фридрих бежал в Кремону.',
  x: parma.x, y: parma.y, tag: 'war', world: true });
  const near = ['emilia', 'lombardy'].includes(G.over.regionAt(G.ox, G.oy));
  log(near ? 'С запада, со стороны Пармы, поднимается чёрный дым. Звонят все колокола Эмилии. Виттория горит!'
    : 'Гонцы несут весть: 18 февраля пармезанцы взяли и сожгли Витторию. Осада Пармы снята.', C.gold);
  chronicle('Пала Виттория: пармезанцы сожгли лагерь императора. Осада Пармы снята.', 'event');
}

// Виттория после падения — пепелище.
function vittoriaVisit(world, city) {
  if (city.siege !== 'vittoria' || parmaSiege()) return;
  if (world.burned) return;
  world.burned = true;
  for (const v of world.villages) v.npcs = [];
  world.actors = world.actors.filter(a => a === G.player || a.kind !== 'npc');
  for (let i = 0; i < world.tiles.length; i++) {
    if (world.building[i] === -1) continue;
    const x = i % world.w, y = (i / world.w) | 0;
    if (TILES[world.tiles[i]].walk && rng.chance(0.6)) world.set(x, y, T.ASH);
    else if (!TILES[world.tiles[i]].walk && rng.chance(0.15)) world.set(x, y, T.RUBBLE);
  }
  log('Виттория — пепелище. Обгорелые балки, пустые шатры, на земле — расколотые щиты с орлом империи. '
    + 'Пармезанцы унесли всё, что могли.', C.dim);
}

// Цены в осаждённой Парме.
function parmaPriceMult(place, good) {
  if (place.id !== 'parma' || !parmaSiege()) return 1;
  return GOODS[good].food ? 2.5 : 1.4;
}
