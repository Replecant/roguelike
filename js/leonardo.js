function fibEnter(world, city) {
  const st = fibStage(), v = world.villages[0];
  if (!v) return;
  // Слух о мастере доходит до Тосканы и Лигурии, пока задание не взято.
  if (st === 0 && ['tuscany', 'liguria'].includes(city.region)) {
    const day = timeInfo().day, pisa = G.over.cities.find(c => c.id === 'pisa');
    if (pisa && !G.news.some(n => n.fib && day - n.day < 30))
      addNews({ day, fib: true, x: pisa.x, y: pisa.y, tag: 'trade',
        text: 'В Пизе старый мастер Леонардо, сын Боначчи, тот, что учил купцов индийскому счёту, — сам не свой: пропала его книга. Ищет толкового человека.' });
  }
  for (const [id, d] of Object.entries(FIB_PEOPLE)) {
    const here = d.city ? city.id === d.city : city.name === d.place;
    if (!here || st < d.from || v.npcs.some(n => n.fib === id)) continue;
    const home = { x: v.cx - 6, y: v.cy - 3, w: 13, h: 7, building: -1 };
    const spot = findFreeIn(world, home) || findFreeIn(world, { x: v.x0, y: v.y0, w: v.w, h: v.h, building: -1 });
    if (!spot) continue;
    const npc = makeNpc('peasant', v, home, spot[0], spot[1]);
    Object.assign(npc, { name: d.name, title: d.title, female: !!d.female, greeting: d.greeting, special: 'fib', fib: id, portrait: d.portrait, color: '#e0d0a0' });
    v.npcs.push(npc);
    world.actors.push(npc);
  }
}

function fibOptions(npc) {
  const p = G.player, st = fibStage(), opts = [{ label: 'Что нового?', act: () => newsReply(npc) }];
  const bobbio = G.over.cities.find(c => c.name === 'Бобьо'), genoa = G.over.cities.find(c => c.id === 'genoa');
  const pisa = G.over.cities.find(c => c.id === 'pisa');
  switch (npc.fib) {
    case 'leonardo':
      opts.push({ label: 'Расскажите о счёте', act: () => `«${rng.pick(LEONARDO_LORE)}»` });
      if (st === 0) opts.push({ label: 'Говорят, у вас пропала книга?', act: () => {
        setFib(1);
        chronicle('Леонардо Пизанский попросил найти его пропавшую книгу.', 'quest');
        return 'Старик вздыхает. «Пропала. "Di minor guisa" — о торговом счёте, на малый лад, для лавочников и подмастерьев. Единственный список. '
          + `Я одолжил его генуэзцу, Оберто Скотто, — учить сыновей. А этой весной Оберто умер. Я писал вдове — ни ответа. Мне до Генуи не доехать: ${dirTo(pisa, genoa)} отсюда, а мне семьдесят семь. `
          + 'Найди книгу, добрый человек. Я не богат, но в долгу не останусь».';
      } });
      if (st >= 1 && st <= 3) opts.push({ label: 'О книге…', act: () => '«Ну что? Нашёл? Не торопись, но и не медли: мне, знаешь ли, медлить уже некогда».' });
      if (st === 4) opts.push({ label: 'Вот ваша книга, мастер', act: () => fibReward() });
      if (st >= 5) {
        const price = p.priceBuy(6), day = timeInfo().day;
        opts.push({ label: `Поучиться счёту у мастера (${price} мон.)`, act: () => {
          if (p.fibLessonDay === day) return '«Хватит на сегодня. Голова — не мешок, сразу не набьёшь».';
          if (p.coins < price) return '«Даром учу только детей коммуны. Ты, уж прости, не ребёнок».';
          p.coins -= price; p.fibLessonDay = day;
          passTime(90);
          trainSkill(p, 'trade', 8);
          return rng.pick(['Вы считаете проценты по векселю и учитесь делить барыш между тремя компаньонами. «Видишь? А римскими цифрами ты бы до вечера бился».',
            'Мастер показывает, как проверять счёт девяткой. «Обманщик ошибается всегда в одну сторону — в свою».']);
        } });
      }
      break;
    case 'widow':
      if (st === 1) opts.push({ label: 'Я ищу книгу мастера Леонардо', act: () => {
        setFib(2);
        return '«Книгу? У Оберто были книги, да. Он вечно сидел над счетами. Когда он умер, пришли заимодавцы, и всё описал нотарий, сер Гульельмо. '
          + 'Что продано, кому — у него в протоколах. Ищи его, он где-то здесь, у рынка. И передай мастеру: я не со зла не ответила. Я не умею читать».';
      } });
      break;
    case 'notary':
      if (st === 2) {
        const fee = p.priceBuy(15);
        const found = () => {
          setFib(3);
          return 'Нотарий листает протокол. «Вот: "Item, liber unus de abaco, in papyro…" — продан за четыре лиры брату Амброджо, библиотекарю аббатства Бобьо, '
            + `для скриптория». Бобьо — ${dirTo(genoa, bobbio)} отсюда, в горах над Треббией. «Монахи скупают всё, где есть буквы. Читать не всегда умеют, но скупают».`;
        };
        opts.push({ label: `Посмотреть опись Оберто Скотто (${fee} мон.)`, act: () => {
          if (p.coins < fee) return `«${coins(fee)}. В Генуе даром даже солнце не светит».`;
          p.coins -= fee;
          return found();
        } });
        if (skillLevel(p, 'speech') >= 2) opts.push({ label: 'Уговорить посмотреть даром (красноречие)', act: () => { trainSkill(p, 'speech', 2); return '«Ну, раз для старика Леонардо… Он учил считать моего отца». ' + found(); } });
        if (skillLevel(p, 'letters') >= 2) opts.push({ label: 'Я сам прочту протокол (грамота)', act: () => { trainSkill(p, 'letters', 2); return 'Нотарий удивлённо пододвигает тебе тетрадь: «Грамотный? Ну, смотри, только не запачкай». ' + found(); } });
      }
      break;
    case 'librarian':
      if (st === 3 && !p.story.fibBanned) {
        const price = p.priceBuy(p.story.fibCaught ? 300 : 150);
        opts.push({ label: 'Мне нужна книга «Di minor guisa»', act: () => '«А, торговая книжица с индийскими знаками. Брат Тедальдо как раз переписывает её. '
          + 'Отдать? Аббатство купило её на свои деньги. Внеси дар — или помоги в скриптории: нам нужны руки, что умеют писать».' });
        opts.push({ label: `Выкупить книгу — дар аббатству (${price} мон.)`, act: () => {
          if (p.coins < price) return `«${coins(price)} — столько стоят пергамент, чернила и труд брата Тедальдо».`;
          p.coins -= price;
          addPiety(2, 'Дар монастырю.');
          setFib(4);
          return 'Библиотекарь заворачивает книгу в холстину. «Копию мы уже начали — доделаем по памяти. Отдай мастеру с поклоном от Бобьо».';
        } });
        opts.push({ label: 'Отработать в скриптории (три дня)', act: () => {
          if (skillLevel(p, 'letters') < 2) return '«Ты пишешь как курица лапой. Испортишь пергамент — а он дороже тебя». (Нужна грамота 2.)';
          passTime(3 * 1440);
          p.food = Math.max(p.food, 70); p.fatigue = Math.min(p.fatigue, 30);
          trainSkill(p, 'letters', 25);
          addPiety(3, 'Три дня труда в скриптории.');
          setFib(4);
          return 'Три дня ты сидишь в холодном скриптории рядом с братом Тедальдо, переписывая индийские знаки, которые монахи боятся перепутать. '
            + 'Монахи кормят тебя бобами и молятся за тебя. На четвёртое утро копия готова — и библиотекарь отдаёт тебе подлинник.';
        } });
        opts.push({ label: 'Унести книгу ночью тайком', act: () => {
          const ok = rng.chance(0.3 + skillLevel(p, 'stealth') * 0.1);
          addPiety(-6, 'Ты украл из монастыря.');
          trainSkill(p, 'stealth', 4);
          if (ok) {
            setFib(4);
            return 'Ночью ты пробираешься в скрипторий. Лунный свет, запах воска, книга на пюпитре рядом с недописанной копией. Ты уходишь, не скрипнув дверью. Утром тебя здесь уже не будет.';
          }
          p.story.fibCaught = true;
          if (p.story.fibTried) p.story.fibBanned = true;
          p.story.fibTried = true;
          return '«Вор!» — брат-привратник хватает тебя за руку у самой двери. Тебя выталкивают за ворота. '
            + (p.story.fibBanned ? 'Больше тебя в Бобьо не пустят.' : '«Теперь — только за триста. И то если аббат простит».');
        } });
      } else if (p.story.fibBanned) opts.push({ label: 'О книге…', act: () => '«Вору здесь отвечать не станут. Уходи».' });
      if (!p.story.fibBanned) opts.push(...libraryOptions(npc));
      break;
  }
  opts.push({ label: 'Уйти', act: () => null });
  return opts;
}

function fibReward() {
  const p = G.player;
  setFib(5);
  p.coins += 120;
  p.gainXp(80);
  addFame(8, 'вернул Леонардо Пизанскому его пропавшую книгу');
  trainSkill(p, 'trade', 20);
  trainSkill(p, 'letters', 10);
  p.story.fibLetter = true;
  chronicle('Вернул Леонардо Пизанскому книгу «Di minor guisa». Мастер дал рекомендательное письмо.', 'quest');
  log('Получено: 120 мон., 80 опыта, рекомендательное письмо мастера Леонардо (купцы уступают в цене).', C.gold);
  return 'Старик долго гладит переплёт, шевелит губами, перелистывает. «Она. Она! Даже пятно от вина на сорок третьем листе — моё». '
    + 'Он достаёт кошель, а потом садится писать. «Вот тебе ещё письмо — к купцам Пизы, Генуи и Флоренции: что ты человек честный и толковый. '
    + 'У нас, торговых людей, такое письмо стоит больше денег. И приходи учиться счёту — для тебя у меня время найдётся».';
}
