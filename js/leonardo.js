function fibStage() { const p = G.player; p.story = p.story || {}; return p.story.fib || 0; }
function setFib(n) {
  const p = G.player;
  p.story.fib = n;
  let q = p.quests.find(q => q.id === 'fib');
  if (n >= 5) { p.quests = p.quests.filter(x => x !== q); return; }
  if (!q) {
    q = { id: 'fib', type: 'story', label: 'Пропавшая книга Леонардо', need: 1, have: 0, reward: 0, xp: 0, done: false, day: timeInfo().day,
      giverName: 'Леонардо Пизанский', fromName: 'Пиза' };
    p.quests.push(q);
  }
  q.text = FIB_TEXT[n];
}

