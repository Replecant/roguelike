// ─── Непобедимое Солнце ────────────────────────────────────────────
// В первом митреуме, куда спустится герой, у входа бродит дух Гая Валерия —
// гелиодрома, «посланника Солнца», убитого, когда христиане разоряли святилище.
// Его таинство прервали, бык не был заклан, и он не может уйти. Он проводит
// героя по ступеням посвящения — как их знали митраисты:
//   1 Ворон (Corax)  — священная трапеза: хлеб и вино;
//   2 Воин (Miles)   — венец на мече: принять его — значит провалить испытание
//                       («Митра — мой венец», как говорил Тертуллиан о воинах Митры);
//   3 Лев (Leo)      — очищение рук мёдом: лев — огонь, а огонь враждебен воде;
//   4 Факелоносцы    — зажечь Кавта (факел вверх, восход) и затем Каутопата
//                       (факел вниз, закат) у рельефа на дне;
//   5 Бык            — из тьмы выходит бык; заклать его, как Митра в пещере.
//   6 — исполнено: благословение Непобедимого Солнца.
// Это языческий обряд: благочестие падает, Михаил и Бенедикт не простят.

const MITHRAS_STEPS = {
  1: 'Ступень Ворона: принести духу хлеб (дорожный провиант) и вино (бочонок с рынка) для священной трапезы.',
  2: 'Ступень Воина: дух поднесёт венец на острие меча. Помни, что говорил гелиодром о воинах Митры.',
  3: 'Ступень Льва: очистить руки для таинства. Лев — огонь. Купить мёд можно у травницы.',
  4: 'Зажечь факелы Кавта (↑) и Каутопата (↓) у рельефа на дне митреума — в порядке дня: от восхода к закату.',
  5: 'Заклать быка, вышедшего из тьмы, у рельефа на дне митреума.',
};

function mithrasStage() {
  const p = G.player;
  p.story = p.story || {};
  return p.story.mithras || 0;
}

function setMithras(n, text) {
  const p = G.player;
  p.story.mithras = n;
  let q = p.quests.find(q => q.id === 'mithras');
  if (n >= 6) { p.quests = p.quests.filter(x => x !== q); return; }
  if (!q) {
    q = { id: 'mithras', type: 'story', label: 'Непобедимое Солнце', need: 1, have: 0, reward: 0, xp: 0, done: false,
      day: timeInfo().day, giverName: 'Дух гелиодрома Гая Валерия' };
    p.quests.push(q);
  }
  const site = G.over.sites.find(s => s.id === p.story.mithrasSite);
  q.fromName = site && site.name;
  q.text = text || MITHRAS_STEPS[n];
}

// Дух встречается в первом митреуме, куда спустился герой.
function mithrasVisit(world) {
  const p = G.player, site = world.site;
  if (!site || site.type !== 'mithraeum' || world.depth !== 0) return;
  if (mithrasStage() >= 6) { world.actors = world.actors.filter(a => a.special !== 'mithras'); return; }
  p.story = p.story || {};
  if (!p.story.mithrasSite) p.story.mithrasSite = site.id;
  if (p.story.mithrasSite !== site.id || world.actors.some(a => a.special === 'mithras')) return;
  const [ux, uy] = world.up;
  const spots = [];
  for (let dy = -4; dy <= 4; dy++) for (let dx = -4; dx <= 4; dx++) {
    const d = Math.max(Math.abs(dx), Math.abs(dy));
    if (d >= 2 && world.free(ux + dx, uy + dy) && world.get(ux + dx, uy + dy) !== T.STAIRS_UP) spots.push([ux + dx, uy + dy]);
  }
  if (!spots.length) return;
  const [x, y] = spots[0];
  const village = { city: site, npcs: [] };
  const npc = {
    kind: 'npc', role: 'spirit', special: 'mithras', village, home: { x, y, w: 1, h: 1, building: -1 }, x, y,
    name: 'Гай Валерий', title: 'Дух гелиодрома', female: false, glyph: '@', color: '#f0c060', energy: 0, portrait: 'pagan_m1',
    greeting: 'Nama! Живой… Тысячу лет здесь не звучали шаги того, кто дышит. Не бойся, я не причиню зла. Я лишь не могу уйти.',
  };
  village.npcs.push(npc);
  world.actors.push(npc);
  if (mithrasStage() === 0) log('У стены стоит бледная фигура в красном плаще и фригийском колпаке. Она смотрит на тебя — и не нападает.', C.violet);
}

