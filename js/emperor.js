function emperorGreeting(npc) {
  if (G.player.is('saracen')) return 'Ва-алейкум ас-салям. Мои лучники из Лючеры — лучшие в Италии. Ты из них? Тогда ты дома.';
  return rng.pick(FREDERICK_GREETINGS);
}

function emperorOptions(npc) {
  const talk = (label, key) => ({ label, act: () => `«${rng.pick(FREDERICK_TALK[key])}»` });
  return [talk('Как идёт осада?', 'siege'), talk('Что вы думаете о папе?', 'pope'), talk('Расскажите о соколах', 'falcons'),
    talk('О мудрецах и науках', 'wisdom'), talk('О законах вашего королевства', 'laws'),
    emperorErrand(npc)];
}

// Поручение императора — только тому, о ком говорят в тавернах.
function emperorErrand(npc) {
  const p = G.player;
  p.story = p.story || {};
  return { label: 'Могу ли я послужить императору?', act: () => {
    if (fameOf(p) < 30) return '«Ты? Мне служат князья, рыцари и лучшие стрелки Италии. '
      + 'Приходи, когда о тебе заговорят в тавернах от Сицилии до Альп, — тогда посмотрим».';
    if (p.story.emperorErrand) return '«Ты уже выполняешь моё поручение — или выполнил. Император не повторяет просьб».';
    const cremona = G.over.cities.find(c => c.id === 'cremona');
    if (!cremona || p.quests.length >= MAX_QUESTS) return '«Вижу, у тебя и так полны руки. Приходи, когда освободишься».';
    p.story.emperorErrand = true;
    const days = 6, reward = 160;
    acceptQuest(npc, {
      type: 'deliver', item: 'Письмо императора королю Энцо', to: cremona.id, toName: placeTitle(cremona), toRole: 'elder',
      toTitle: roleTitle(cremona, 'elder'), deadline: timeInfo().day + days, reward, xp: 40,
      text: `Доставить в Кремону письмо императора для его сына, короля Энцо; отдать подесте, тот передаст. Срок — ${days} дн. Плата — ${coins(reward)} золотыми августалами.`,
    });
    chronicle('Император Фридрих II поручил доставить письмо своему сыну, королю Энцо.', 'event');
    addFame(3, 'получил поручение от самого императора');
    return `«А, ${p.name}. Я слышал о тебе: говорят, ты ${(p.deeds || ['кое-что сделал'])[0]}. Хорошо. Вот письмо моему сыну Энцо, он в Кремоне. `
      + 'Отдашь подесте — тот знает, как передать. Не вскрывай: сломаешь печать — сломаю тебе шею. В Кремоне заплатят августалами, '
      + 'моими золотыми: на них мой профиль, как у цезарей». Он запечатывает письмо перстнем с орлом.';
  } };
}
