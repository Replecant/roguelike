function emperorGreeting(npc) {
  const p = G.player;
  if (crusadeStage() >= 2 && crusadeStage() < 5)
    return 'От тебя пахнет ладаном Капоччи. Человек легата в моём лагере? Говори быстро — пока я в добром расположении духа.';
  if (p.is('saracen')) return 'Ва-алейкум ас-салям. Мои лучники из Лючеры — лучшие в Италии. Ты из них? Тогда ты дома.';
  return rng.pick(FREDERICK_GREETINGS);
}

function emperorOptions(npc) {
  const p = G.player, opts = [];
  const talk = (label, key) => ({ label, act: () => `«${rng.pick(FREDERICK_TALK[key])}»` });
  opts.push(talk('Как идёт осада?', 'siege'), talk('Что вы думаете о папе?', 'pope'), talk('Расскажите о соколах', 'falcons'),
    talk('О мудрецах и науках', 'wisdom'), talk('О законах вашего королевства', 'laws'));
  if (!p.story) p.story = {};
  const enemy = crusadeStage() >= 2 && crusadeStage() < 5;
  if (!p.story.emperorErrand && !enemy) opts.push({ label: 'Могу ли я послужить императору?', act: () => {
    const cremona = G.over.cities.find(c => c.id === 'cremona');
    if (!cremona || p.quests.length >= MAX_QUESTS) return '«Вижу, у тебя и так полны руки. Приходи, когда освободишься».';
    p.story.emperorErrand = true;
    const days = 6, reward = 160;
    acceptQuest(npc, {
      type: 'deliver', item: 'Письмо императора королю Энцо', to: cremona.id, toName: placeTitle(cremona), toRole: 'elder',
      toTitle: roleTitle(cremona, 'elder'), deadline: timeInfo().day + days, reward, xp: 40,
      text: `Доставить в Кремону письмо императора для его сына, короля Энцо; отдать подесте, тот передаст. Срок — ${days} дн. Плата — ${coins(reward)} золотыми августалами.`,
    });
    chronicle('Император Фридрих II поручил доставить письмо своему сыну, королю Энцо.', 'event');
    return '«Хорошо. Вот письмо моему сыну Энцо, он в Кремоне. Отдашь подесте — тот знает, как передать. Не вскрывай: сломаешь печать — '
      + 'сломаю тебе шею. В Кремоне тебе заплатят августалами — моими золотыми. На них мой профиль, как у цезарей». '
      + 'Он запечатывает письмо перстнем с орлом.';
  } });
  if (enemy) opts.push({ label: 'Я служу Церкви', act: () => '«Церкви — или легату? Это не одно и то же, хотя в Лионе об этом забыли. Ступай. '
    + 'Сегодня я тебя отпускаю — завтра мои сарацины могут оказаться менее любезны».' });
  return opts;
}
