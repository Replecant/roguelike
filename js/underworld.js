'use strict';

// ─── Путь в подземный мир ──────────────────────────────────────────
// Цепочка фламина из селения язычников:
//   1 — доказать, что не слуга попов: принести в дар подземным богам трофей
//       хозяина любого подземелья;
//   2 — добыть золотую ветвь в пещере Сивиллы в Кумах (без неё живому
//       в царство мёртвых не войти — так у Вергилия);
//   3 — вернуться с ветвью: фламин откроет путь к жерлу Этны;
//   4 — спуститься через шесть кругов и одолеть Дита. 5 — путь пройден.

// Трофеи хозяев подземелий, годные в дар.
const UNDERWORLD_GIFTS = ['gold_mask', 'charun_hammer', 'grimoire', 'mithras_crown', 'serpent_scale', 'silver_heart',
  'crusader_cross', 'hecate_collar'];

function storyStage() {
  const p = G.player;
  p.story = p.story || {};
  return p.story.inferi || 0;
}

function setStage(n, text) {
  const p = G.player;
  p.story.inferi = n;
  let q = p.quests.find(q => q.id === 'inferi');
  if (n >= 5) { p.quests = p.quests.filter(x => x !== q); return; }
  if (!q) {
    q = { id: 'inferi', type: 'story', label: 'Путь в подземный мир', need: 1, have: 0, reward: 0, xp: 0, done: false, day: timeInfo().day };
    p.quests.push(q);
  }
  q.text = text;
}

function flamenOptions(npc) {
  const p = G.player, place = npc.village.city, stage = storyStage(), opts = [];
  if (crusadeStage() >= 2 && stage < 4) {
    opts.push({ label: 'Правда ли, что под Этной вход в царство мёртвых?', act: () =>
      'Фламин смотрит на тебя, как на волка у овчарни. «Мы знаем, кто тебя послал. Уходи, слуга попов, пока тебя отпускают»' });
    return opts;
  }
  const bind = () => {
    const q = p.quests.find(q => q.id === 'inferi');
    if (q) { q.giverName = `${npc.title} ${npc.name}`; q.fromName = place.name; }
  };
  if (stage === 0) {
    opts.push({ label: 'Правда ли, что под Этной вход в царство мёртвых?', act: () => {
      setStage(1, `Фламин ${npc.name} (${place.name}) знает путь в подземный мир под Этной. Но сперва надо доказать, что ты не слуга попов: `
        + 'принести в дар подземным богам трофей хозяина любого подземелья — маску проконсула, молот Харуна, венец Митры, сердце горы…');
      bind();
      chronicle(`Фламин ${npc.name} из селения ${place.name} заговорил о пути в подземный мир.`, 'event');
      return 'Правда. Facilis descensus Averno — лёгок спуск. Трудно вернуться. Мы, потомки тех, кто жил здесь при Цезарях, '
        + 'помним путь. Но я не открою его тому, кто пахнет ладаном ваших церквей. Принеси дар подземным богам — '
        + 'то, что взято у хозяина глубин, у того, кто правил под землёй. Тогда поговорим.';
    } });
    return opts;
  }
  if (stage === 1) {
    const gift = UNDERWORLD_GIFTS.find(id => p.trophies[id] && p.trophies[id].count > 0);
    if (gift) {
      opts.push({ label: `Принести в дар подземным богам: ${p.trophies[gift].name.toLowerCase()}`, act: () => {
        const tr = p.trophies[gift];
        tr.count--;
        if (!tr.count) delete p.trophies[gift];
        addPiety(-6, 'Ты принёс жертву языческим богам.');
        if (p.patron === 'michael' || p.patron === 'benedict') breakTaboo('Жертва языческим богам.');
        const cumae = G.over.sites.find(s => s.id === 'sibyl');
        revealTomb(cumae);
        setStage(2, 'Добыть золотую ветвь в пещере Сивиллы в Кумах, у Неаполя (отмечена на карте). Её стережёт пёс Гекаты.');
        bind();
        log('На карте отмечено: пещера Сивиллы в Кумах.', C.gold);
        chronicle('Принёс жертву подземным богам на алтаре язычников.', 'faith');
        return 'Фламин кладёт дар на алтарь и долго шепчет на латыни, древней, чем латынь ваших священников. Огонь вспыхивает зелёным. '
          + '«Боги приняли. Теперь слушай: живой не войдёт к мёртвым без золотой ветви. Она растёт в роще Прозерпины, '
          + 'а вход в рощу — пещера Сивиллы в Кумах, у Неаполя. Ветвь стережёт пёс Гекаты. Принеси её мне».';
      } });
    } else opts.push({ label: 'О даре подземным богам…', act: () =>
      'Ты пришёл с пустыми руками. Спустись в гробницу, в катакомбы, в рудник — туда, где правит хозяин глубин. Одолей его и принеси то, что он хранил.' });
    return opts;
  }
  if (stage === 2 || stage === 3) {
    if (hasItem('golden_bough')) {
      opts.push({ label: 'Я принёс золотую ветвь', act: () => {
        const etna = G.over.sites.find(s => s.id === 'inferi');
        revealTomb(etna);
        setStage(4, 'Спуститься в подземный мир через жерло Этны (отмечено на карте) — шесть кругов, до чертога Дита. Золотая ветвь должна быть при тебе.');
        bind();
        log('На карте отмечено: жерло Этны.', C.gold);
        chronicle('Фламин указал путь в подземный мир: жерло Этны.', 'event');
        return 'Фламин касается ветви кончиками пальцев, и его глаза влажнеют. «Я видел её только во сне, как мой отец и его отец. '
          + 'Иди на Сицилию, к Этне. На восточном склоне — трещина, из которой тянет серой. Держи ветвь при себе: '
          + 'Харон перевезёт тебя через Стикс, а жар не тронет. Но Цербера ветвь не усмирит. И помни: спуститься легко».';
      } });
    } else opts.push({ label: 'О золотой ветви…', act: () => 'Пещера Сивиллы — в Кумах, у Неаполя. Ветвь растёт за ней, в роще Прозерпины. Не возвращайся без неё.' });
    return opts;
  }
  if (stage === 4) opts.push({ label: 'О пути через Этну…', act: () =>
    'Шесть кругов: жерло, кузни Вулкана, поля асфоделей, Стикс, Тартар — и чертог Дита. Держи ветвь при себе. И возвращайся живым — это труднее.' });
  if (stage >= 5) opts.push({ label: 'Я вернулся из чертога Дита', act: () =>
    'Фламин долго молчит, а потом склоняет голову — впервые перед чужаком. «Ты сделал то, чего не делал никто со времён Энея. Боги запомнят твоё имя. И мы тоже».' });
  return opts;
}

// Ветвь из рощи Прозерпины.
function takeBough() {
  const p = G.player;
  if (hasItem('golden_bough')) { log('Ветвь уже у тебя. Дерево молчит.', C.dim); return true; }
  p.bag.push(makeItem('golden_bough'));
  if (storyStage() < 3) setStage(3, 'Вернуться к фламину с золотой ветвью.');
  log('Ты отламываешь ветвь — и она легко поддаётся, как и обещал Вергилий: «если судьба зовёт тебя». Листья звенят, как монеты. '
    + 'Золотая ветвь — в котомке. Возвращайся к фламину.', C.gold);
  chronicle('Добыл золотую ветвь в пещере Сивиллы.', 'find');
  return true;
}

// Дит повержен.
function underworldConquered() {
  if (storyStage() >= 5) return;
  setStage(5);
  log('Владыка мёртвых падает на колено — и смеётся. «Живой в моём чертоге… Возвращайся наверх, герой. Мы ещё встретимся: '
    + 'все встречаются со мной». Чертог дрожит, и тени расступаются перед тобой.', C.gold);
  chronicle('Спустился в подземный мир через жерло Этны и одолел Дита, владыку мёртвых. Такого не было со времён Энея.', 'boss');
}
